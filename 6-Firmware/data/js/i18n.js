const LANG_KEY = 'iotester.lang';

/**
 * IT: Lingua attuale: parametro ?lang, poi quella salvata, poi quella del browser (italiano o inglese).
 * EN: Current language: ?lang parameter, then the saved one, then the browser's (Italian or English).
 */
function getLang() {
  const param = new URLSearchParams(location.search).get('lang');
  if (param && I18N[param]) return param;
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && I18N[saved]) return saved;
  } catch (e) { /* IT: memoria del browser non disponibile / EN: browser storage unavailable */ }
  return (navigator.language || 'it').toLowerCase().startsWith('it') ? 'it' : 'en';
}

/**
 * IT: Restituisce il testo tradotto e sostituisce le variabili {nome}.
 * EN: Returns the translated text and replaces {name} variables.
 */
function t(key, vars = {}) {
  const dict = I18N[getLang()] || I18N.it;
  const text = dict[key] ?? I18N.it[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? vars[name] : m));
}

/**
 * IT: Traduce gli elementi con data-i18n (testo) e data-i18n-title (title/aria-label); aggiorna i pulsanti lingua.
 * EN: Translates elements with data-i18n (text) and data-i18n-title (title/aria-label); updates language buttons.
 */
function applyI18n() {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute('aria-label', el.title);
  });
  document.querySelectorAll('[data-lang]').forEach((btn) => {
    btn.setAttribute('aria-pressed', String(btn.dataset.lang === lang));
  });
}

/**
 * IT: Cambia lingua, la salva e ritraduce la pagina; avvisa il resto dell'app con l'evento "langchange".
 * EN: Changes language, saves it and re-translates the page; notifies the app with a "langchange" event.
 */
function setLang(lang) {
  try { localStorage.setItem(LANG_KEY, lang); } catch (e) { /* IT/EN: vedi sopra / see above */ }
  const url = new URL(location.href);
  if (url.searchParams.has('lang')) {            // IT: il parametro vincerebbe sulla scelta / EN: the parameter would override the choice
    url.searchParams.delete('lang');
    history.replaceState(null, '', url);
  }
  applyI18n();
  document.dispatchEvent(new Event('langchange'));
}
